class DenoisingDataset(Dataset):
    """
    Dataset pour DnCNN avec normalisation GLOBALE.

    IMPORTANT:
    - La normalisation utilise les statistiques GLOBALES (mean_global, std_global)
    - Le bruit est ajouté APRÈS normalisation
    - Retourne (noisy_normalized, noise_normalized)
    """

    def __init__(self, root_dir, pattern="*.jpg", patch_size=40,
                 noise_sigma=25, mean_global=0.0, std_global=1.0,
                 patches_per_image=100):
        """
        Args:
            root_dir: dossier contenant les images
            pattern: motif pour glob
            patch_size: taille des patches
            noise_sigma: niveau de bruit (0-255)
            mean_global: moyenne globale calculée sur toute la base
            std_global: écart-type global calculé sur toute la base
            patches_per_image: nombre de patches extraits par image
        """
        self.list_im = sorted(glob.glob(os.path.join(root_dir, pattern)))
        self.patch_size = patch_size
        self.noise_sigma = noise_sigma / 255.0  # Normalisation en [0, 1]
        self.mean_global = mean_global
        self.std_global = std_global
        self.patches_per_image = patches_per_image

        print(f"\n✓ Dataset initialisé:")
        print(f"  Images: {len(self.list_im)}")
        print(f"  Patches par image: {patches_per_image}")
        print(f"  Total patches: {len(self)}")
        print(f"  Patch size: {patch_size}×{patch_size}")
        print(f"  Noise σ: {noise_sigma}")
        print(f"  Normalisation: μ={mean_global:.4f}, σ={std_global:.4f}")

    def __len__(self):
        return len(self.list_im) * self.patches_per_image

    def __getitem__(self, idx):
        # Sélectionne une image (avec répétition)
        img_idx = idx // self.patches_per_image
        img_path = self.list_im[img_idx]

        # Charge l'image
        img = Image.open(img_path)

        # Convertit en grayscale (méthode PIL standard)
        if img.mode != 'L':
            img = img.convert('L')

        # Convertit en array [0, 1]
        img_array = np.array(img, dtype=np.float32) / 255.0

        # Extrait un patch aléatoire
        h, w = img_array.shape

        # Assure que l'image est assez grande
        if h < self.patch_size or w < self.patch_size:
            # Resize si nécessaire
            new_h = max(h, self.patch_size)
            new_w = max(w, self.patch_size)
            img = img.resize((new_w, new_h), Image.BILINEAR)
            img_array = np.array(img, dtype=np.float32) / 255.0
            h, w = img_array.shape

        # Position aléatoire
        top = np.random.randint(0, h - self.patch_size + 1)
        left = np.random.randint(0, w - self.patch_size + 1)

        # Extrait le patch PROPRE [0, 1]
        clean_patch = img_array[top:top+self.patch_size,
                                left:left+self.patch_size].copy()

        # ========================================
        # ÉTAPE 1: NORMALISATION GLOBALE
        # ========================================
        clean_normalized = (clean_patch - self.mean_global) / self.std_global

        # ========================================
        # ÉTAPE 2: AJOUT DU BRUIT (sur données normalisées)
        # ========================================
        # Le bruit doit aussi être normalisé par std_global
        noise_normalized = np.random.randn(*clean_normalized.shape).astype(np.float32) * (self.noise_sigma / self.std_global)

        # Image bruitée normalisée
        noisy_normalized = clean_normalized + noise_normalized

        # Convertit en tenseurs [1, H, W]
        clean_normalized = torch.from_numpy(clean_normalized).unsqueeze(0)
        noisy_normalized = torch.from_numpy(noisy_normalized).float().unsqueeze(0)
        noise_normalized = torch.from_numpy(noise_normalized).float().unsqueeze(0)

        # Pour évaluation: garde aussi les versions originales [0, 1]
        clean_original = torch.from_numpy(clean_patch).unsqueeze(0)

        return {
            'noisy': noisy_normalized,        # Entrée du réseau
            'noise': noise_normalized,        # Target du réseau
            'clean_original': clean_original, # Pour calcul PSNR
        }


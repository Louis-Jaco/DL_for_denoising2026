def denormalize(tensor_normalized, mean_global, std_global):
    """
    Dénormalise un tensor.

    Args:
        tensor_normalized: tensor normalisé
        mean_global: moyenne globale utilisée pour la normalisation
        std_global: écart-type global

    Returns:
        tensor dénormalisé dans [0, 1]
    """
    return tensor_normalized * std_global + mean_global


def compute_psnr(img1, img2):
    """
    Calcule le PSNR entre deux images.

    Args:
        img1, img2: tensors [B, C, H, W] avec valeurs en [0, 1]

    Returns:
        PSNR moyen sur le batch (dB)
    """
    mse = F.mse_loss(img1, img2, reduction='mean')
    if mse == 0:
        return float('inf')
    return 20 * torch.log10(torch.tensor(1.0)) - 10 * torch.log10(mse)


def visualize_results(model, dataloader, device, mean_global, std_global, num_samples=4):
    """
    Visualise les résultats de débruitage.
    """
    model.eval()

    # Récupère un batch
    batch = next(iter(dataloader))

    with torch.no_grad():
        noisy = batch['noisy'][:num_samples].to(device)
        clean_original = batch['clean_original'][:num_samples]

        # Prédiction du bruit (normalisé)
        noise_pred = model(noisy)

        # Image débruitée (normalisée)
        denoised_normalized = noisy - noise_pred

        # Dénormalisation
        denoised = denormalize(denoised_normalized.cpu(), mean_global, std_global)
        denoised = torch.clamp(denoised, 0, 1)

        # Dénormalise aussi noisy pour affichage
        noisy_denorm = denormalize(noisy.cpu(), mean_global, std_global)
        noisy_denorm = torch.clamp(noisy_denorm, 0, 1)

    # Calcul PSNR
    psnr = compute_psnr(denoised, clean_original)

    # Affichage
    fig, axes = plt.subplots(3, num_samples, figsize=(16, 10))

    for i in range(num_samples):
        # Image propre
        axes[0, i].imshow(clean_original[i, 0].cpu().numpy(), cmap='gray', vmin=0, vmax=1)
        axes[0, i].set_title(f'Propre {i+1}')
        axes[0, i].axis('off')

        # Image bruitée
        axes[1, i].imshow(noisy_denorm[i, 0].cpu().numpy(), cmap='gray', vmin=0, vmax=1)
        axes[1, i].set_title(f'Bruitée {i+1}')
        axes[1, i].axis('off')

        # Image débruitée
        axes[2, i].imshow(denoised[i, 0].cpu().numpy(), cmap='gray', vmin=0, vmax=1)
        axes[2, i].set_title(f'Débruitée {i+1}')
        axes[2, i].axis('off')

    plt.suptitle(f'Résultats de débruitage - PSNR moyen: {psnr:.2f} dB',
                 fontsize=14, y=0.98)
    plt.tight_layout()
    plt.show()

    return psnr.item()


class DnCNN(nn.Module):
    """
    DnCNN Network pour le débruitage d'images.
    Architecture basée sur Zhang et al. 2017
    """

    def __init__(self, in_channels=1, out_channels=1, depth=17, n_filters=64):
        """
        Args:
            in_channels: nombre de canaux d'entrée (1 pour grayscale)
            out_channels: nombre de canaux de sortie (1 pour grayscale)
            depth: profondeur du réseau (17 pour DnCNN-S)
            n_filters: nombre de filtres (64 dans l'article)
        """
        super(DnCNN, self).__init__()

        self.depth = depth
        layers = []

        # Première couche: Conv + ReLU (PAS de BatchNorm)
        layers.append(nn.Conv2d(in_channels, n_filters,
                               kernel_size=3, padding=1, bias=True))
        layers.append(nn.ReLU(inplace=True))

        # Couches intermédiaires: Conv + BN + ReLU
        for _ in range(depth - 2):
            layers.append(nn.Conv2d(n_filters, n_filters,
                                   kernel_size=3, padding=1, bias=False))
            layers.append(nn.BatchNorm2d(n_filters))
            layers.append(nn.ReLU(inplace=True))

        # Dernière couche: Conv seulement
        layers.append(nn.Conv2d(n_filters, out_channels,
                               kernel_size=3, padding=1, bias=True))

        self.dncnn = nn.Sequential(*layers)

        # Initialisation des poids (He initialization)
        self._initialize_weights()

    def _initialize_weights(self):
        """Initialise les poids selon He et al."""
        for m in self.modules():
            if isinstance(m, nn.Conv2d):
                nn.init.kaiming_normal_(m.weight, mode='fan_out', nonlinearity='relu')
                if m.bias is not None:
                    nn.init.constant_(m.bias, 0)
            elif isinstance(m, nn.BatchNorm2d):
                nn.init.constant_(m.weight, 1)
                nn.init.constant_(m.bias, 0)

    def forward(self, x):
        """
        Forward pass.
        Args:
            x: image bruitée normalisée
        Returns:
            bruit prédit (normalisé)
        """
        return self.dncnn(x)


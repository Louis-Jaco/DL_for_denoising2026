def compute_global_stats(image_folder, pattern="*.jpg", max_images=None):
    """
    Calcule la moyenne et l'écart-type GLOBAL sur toute la base d'images.

    Args:
        image_folder: dossier contenant les images
        pattern: motif pour glob
        max_images: nombre max d'images à analyser (None = toutes)

    Returns:
        mean_global: moyenne globale (scalaire pour grayscale)
        std_global: écart-type global (scalaire pour grayscale)
    """
    print("\n" + "="*60)
    print("CALCUL DES STATISTIQUES GLOBALES")
    print("="*60)

    image_list = sorted(glob.glob(os.path.join(image_folder, pattern)))

    if max_images is not None:
        image_list = image_list[:max_images]

    print(f"Nombre d'images à analyser: {len(image_list)}")

    # Accumulateurs pour calcul en une passe
    sum_pixels = 0.0
    sum_squares = 0.0
    n_pixels = 0

    for img_path in tqdm(image_list, desc="Calcul statistiques"):
        # Charge l'image
        img = Image.open(img_path)

        # Convertit en grayscale (méthode standard)
        if img.mode != 'L':
            img = img.convert('L')

        # Convertit en array [0, 1]
        img_array = np.array(img, dtype=np.float32) / 255.0

        # Accumule
        sum_pixels += img_array.sum()
        sum_squares += (img_array ** 2).sum()
        n_pixels += img_array.size

    # Calcul moyenne et écart-type
    mean_global = sum_pixels / n_pixels
    variance_global = (sum_squares / n_pixels) - (mean_global ** 2)
    std_global = np.sqrt(variance_global)

    print(f"\n✓ Statistiques globales calculées:")
    print(f"  Moyenne: {mean_global:.4f}")
    print(f"  Écart-type: {std_global:.4f}")
    print(f"  Pixels analysés: {n_pixels:,}")

    return mean_global, std_global


def train_epoch(model, dataloader, optimizer, device, mean_global, std_global):
    """Entraîne le modèle sur une époque."""
    model.train()
    total_loss = 0
    total_psnr = 0

    pbar = tqdm(dataloader, desc="Training")
    for batch in pbar:
        # Données normalisées
        noisy = batch['noisy'].to(device)
        noise_target = batch['noise'].to(device)
        clean_original = batch['clean_original'].to(device)

        # Forward
        optimizer.zero_grad()
        noise_pred = model(noisy)

        # Loss: MSE sur le bruit (normalisé)
        loss = F.mse_loss(noise_pred, noise_target)

        # Backward
        loss.backward()
        optimizer.step()

        total_loss += loss.item()

        # Calcul PSNR (sur images dénormalisées)
        with torch.no_grad():
            denoised_norm = noisy - noise_pred
            denoised = denormalize(denoised_norm, mean_global, std_global)
            denoised = torch.clamp(denoised, 0, 1)
            psnr = compute_psnr(denoised, clean_original)
            total_psnr += psnr.item()

        pbar.set_postfix({'loss': f'{loss.item():.4f}', 'psnr': f'{psnr.item():.2f}'})

    return total_loss / len(dataloader), total_psnr / len(dataloader)


def evaluate(model, dataloader, device, mean_global, std_global):
    """Évalue le modèle."""
    model.eval()
    total_loss = 0
    total_psnr = 0

    with torch.no_grad():
        for batch in tqdm(dataloader, desc="Evaluating"):
            noisy = batch['noisy'].to(device)
            noise_target = batch['noise'].to(device)
            clean_original = batch['clean_original'].to(device)

            # Prédiction
            noise_pred = model(noisy)

            # Loss
            loss = F.mse_loss(noise_pred, noise_target)
            total_loss += loss.item()

            # PSNR
            denoised_norm = noisy - noise_pred
            denoised = denormalize(denoised_norm, mean_global, std_global)
            denoised = torch.clamp(denoised, 0, 1)
            psnr = compute_psnr(denoised, clean_original)
            total_psnr += psnr.item()

    return total_loss / len(dataloader), total_psnr / len(dataloader)


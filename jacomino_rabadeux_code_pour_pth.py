class DnCNN(nn.Module):
    """Architecture DnCNN - DOIT être identique à celle utilisée pour l'entraînement"""

    def __init__(self, in_channels=1, out_channels=1, depth=17, n_filters=64):
        super(DnCNN, self).__init__()

        layers = []

        # Première couche
        layers.append(nn.Conv2d(in_channels, n_filters, kernel_size=3, padding=1, bias=True))
        layers.append(nn.ReLU(inplace=True))

        # Couches intermédiaires
        for _ in range(depth - 2):
            layers.append(nn.Conv2d(n_filters, n_filters, kernel_size=3, padding=1, bias=False))
            layers.append(nn.BatchNorm2d(n_filters))
            layers.append(nn.ReLU(inplace=True))

        # Dernière couche
        layers.append(nn.Conv2d(n_filters, out_channels, kernel_size=3, padding=1, bias=True))

        self.dncnn = nn.Sequential(*layers)

    def forward(self, x):
        return self.dncnn(x)


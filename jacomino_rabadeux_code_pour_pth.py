def denoise_image(model, image_path, noise_sigma=25, device='cuda'):
    """
    Débruite une image en utilisant le modèle chargé.

    Args:
        model: Modèle DnCNN chargé
        image_path: Chemin vers l'image à débruiter
        noise_sigma: Niveau de bruit (0-255) - utilisé pour la normalisation
        device: 'cuda' ou 'cpu'

    Returns:
        dict contenant les images propre, bruitée, débruitée
    """
    # Charger l'image
    img = Image.open(image_path).convert('L')
    img_tensor = transforms.ToTensor()(img).unsqueeze(0)  # [1, 1, H, W]

    # Ajouter du bruit
    noise = torch.randn_like(img_tensor) * (noise_sigma / 255.0)
    noisy_img = img_tensor + noise
    noisy_img = torch.clamp(noisy_img, 0, 1)

    # Normalisation (μ=0, σ=1)
    mean = noisy_img.mean()
    std = noisy_img.std()
    noisy_normalized = (noisy_img - mean) / (std + 1e-8)

    # Déplacer sur le device
    noisy_normalized = noisy_normalized.to(device)

    # Prédire le bruit
    with torch.no_grad():
        noise_pred = model(noisy_normalized)

    # Débruiter
    denoised_normalized = noisy_normalized - noise_pred
    denoised = denoised_normalized * std + mean
    denoised = torch.clamp(denoised, 0, 1)

    # Calculer le PSNR
    mse = torch.mean((denoised - img_tensor.to(device)) ** 2)
    psnr = 20 * torch.log10(1.0 / torch.sqrt(mse))

    return {
        'clean': img_tensor.cpu(),
        'noisy': noisy_img.cpu(),
        'denoised': denoised.cpu(),
        'psnr': psnr.item()
    }


def denoise_from_noisy_image(model, noisy_image_path, device='cuda'):
    """
    Débruite une image DÉJÀ bruitée (image réelle ou déjà corrompue).

    Args:
        model: Modèle DnCNN chargé
        noisy_image_path: Chemin vers l'image déjà bruitée
        device: 'cuda' ou 'cpu'

    Returns:
        dict contenant l'image bruitée et débruitée
    """
